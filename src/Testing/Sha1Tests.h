#pragma once

#include "Sha1.h"

namespace Sha1Tests
{
    template<uint32_t N>
    constexpr bool Hashes(const char (&text)[N], const uint8_t (&expected)[Sha1::HashLength])
    {
        Array<uint8_t, N> bytes;
        Span<const char>(text).template CopyTo<uint8_t>(bytes, [](char c) { return static_cast<uint8_t>(c); });

        return Sha1::Compute(bytes.Take(N - 1)).SequenceEquals(expected);
    }

    // FIPS 180's examples.
    static_assert(Hashes("", { 0xDA, 0x39, 0xA3, 0xEE, 0x5E, 0x6B, 0x4B, 0x0D, 0x32, 0x55, 0xBF, 0xEF, 0x95, 0x60, 0x18, 0x90,
        0xAF, 0xD8, 0x07, 0x09 }), "An empty message failed");

    static_assert(Hashes("abc", { 0xA9, 0x99, 0x3E, 0x36, 0x47, 0x06, 0x81, 0x6A, 0xBA, 0x3E, 0x25, 0x71, 0x78, 0x50, 0xC2, 0x6C,
        0x9C, 0xD0, 0xD8, 0x9D }), "A message within a block failed");

    static_assert(Hashes("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq", { 0x84, 0x98, 0x3E, 0x44, 0x1C, 0x3B, 0xD2,
        0x6E, 0xBA, 0xAE, 0x4A, 0xA1, 0xF9, 0x51, 0x29, 0xE5, 0xE5, 0x46, 0x70, 0xF1 }),
        "A message whose length spills into a second block failed");

    // 64 bytes: a whole block, then an ending with nothing left over.
    static_assert(Hashes("0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef", { 0xCE, 0x43, 0x03, 0xF6, 0xB2,
        0x22, 0x57, 0xD9, 0xC9, 0xCF, 0x31, 0x4E, 0xF1, 0xDE, 0xE4, 0x70, 0x7C, 0x6E, 0x1C, 0x13 }),
        "A message of exactly one block failed");
}
